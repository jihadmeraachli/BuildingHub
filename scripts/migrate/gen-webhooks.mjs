// Frankfurt migration, Phase 4 — generate the SQL that (a) purges every
// restored trigger still POSTing to the old Seoul project and (b) recreates
// all Database Webhooks pointing at the NEW dynamic-action, each carrying the
// x-webhook-secret header (0133/H4 forgery guard).
//
//   node scripts/migrate/gen-webhooks.mjs > scripts/migrate/webhooks.sql
//   psql "<NEW_POOLER_URI>" -f scripts/migrate/webhooks.sql
//
// Reads scripts/migration.env: NEW_REF, NEW_ANON_KEY, WEBHOOK_SECRET.
// Dashboard-made webhooks are just triggers on supabase_functions.http_request
// under the hood — creating them in SQL is exactly what the UI does, minus
// the clicking. The dashboard's Webhooks page lists them afterwards.
//
// ⚠️ Companion, NOT covered here: per-function "verify JWT" toggles must be
// replicated when deploying functions. send-reminders, whish-callback and
// areeba-callback authenticate their callers themselves (CRON_SECRET /
// gateway signatures) and need JWT verification OFF; check each function's
// setting on the OLD project before pausing it.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const OLD_REF = 'miyrsnlpftybmudiuhbi';

const envPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'migration.env');
const env = {};
for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
  const m = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
  if (m) env[m[1]] = m[2].trim();
}
const need = (k) => {
  if (!env[k]) { console.error(`-- missing ${k} in scripts/migration.env`); process.exit(1); }
  return env[k];
};
const NEW_REF = need('NEW_REF');
const ANON = need('NEW_ANON_KEY');
const SECRET = need('WEBHOOK_SECRET');

// The webhook inventory (mirror of docs/MIGRATION_FRANKFURT.md Phase 4.2 —
// cross-check against the OLD project's dashboard before pausing it).
const WEBHOOKS = [
  { table: 'profiles',              events: ['UPDATE'] },
  { table: 'issues',                events: ['UPDATE'] },
  { table: 'meetings',              events: ['INSERT'] },
  { table: 'charges',               events: ['INSERT'] },
  { table: 'payments',              events: ['INSERT', 'UPDATE', 'DELETE'] },
  { table: 'dues',                  events: ['INSERT', 'UPDATE', 'DELETE'] },
  { table: 'membership_invites',    events: ['INSERT'] },
  { table: 'adjustments',           events: ['INSERT'] },
  { table: 'payment_request_lines', events: ['INSERT'] },
  { table: 'subscriptions',         events: ['INSERT'] },
  { table: 'invoices',              events: ['INSERT', 'UPDATE'] },
];

const url = `https://${NEW_REF}.supabase.co/functions/v1/dynamic-action`;
const headers = JSON.stringify({
  'Content-Type': 'application/json',
  Authorization: `Bearer ${ANON}`,
  'x-webhook-secret': SECRET,
});

const lines = [];
lines.push('-- Generated by scripts/migrate/gen-webhooks.mjs — do not commit (contains keys).');
lines.push('BEGIN;');
lines.push('');
lines.push('-- 1. Purge every restored trigger that still POSTs to Seoul.');
lines.push(`DO $purge$
DECLARE r RECORD;
BEGIN
  FOR r IN
    SELECT DISTINCT event_object_table AS tbl, trigger_name AS trg
    FROM information_schema.triggers
    WHERE action_statement LIKE '%${OLD_REF}%'
  LOOP
    EXECUTE format('DROP TRIGGER %I ON public.%I', r.trg, r.tbl);
    RAISE NOTICE 'dropped %.%', r.tbl, r.trg;
  END LOOP;
END $purge$;`);
lines.push('');
lines.push('-- 2. Recreate the webhooks against the new project.');
for (const { table, events } of WEBHOOKS) {
  const trg = `wh_${table}_dynamic_action`;
  lines.push(`DROP TRIGGER IF EXISTS "${trg}" ON public.${table};`);
  lines.push(`CREATE TRIGGER "${trg}"
AFTER ${events.join(' OR ')} ON public.${table}
FOR EACH ROW EXECUTE FUNCTION supabase_functions.http_request(
  '${url}', 'POST', '${headers}', '{}', '5000'
);`);
  lines.push('');
}
lines.push('COMMIT;');
lines.push('');
lines.push('-- Verify: this must return ZERO rows.');
lines.push(`SELECT event_object_table, trigger_name FROM information_schema.triggers WHERE action_statement LIKE '%${OLD_REF}%';`);

process.stdout.write(lines.join('\n') + '\n');
